//go:build integration

package service

import (
	"context"
	"os"
	"testing"
	"time"

	"github.com/sweetlife999/chain-of-trades-avito/internal/llm"
)

// Порог. Замерено на qwen2.5:0.5b (q4_K_M) с параметрами из internal/llm: 14 из 19, три
// прогона подряд дают ровно это число. Порог на единицу ниже: тот же промпт в ручном
// пробнике однажды разошёлся с клиентом на один кейс, то есть на результат влияет не
// только текст запроса, но и состояние раннера, а красный тест на ровном месте хуже, чем
// пропущенный минус один кейс.
//
// Провалы, ради которых порог и стоит, другого масштаба: пять тем без payment давали
// 11 из 19 на этом же наборе, а правило дефолта в промпте роняло результат до 6 из 15.
const botAccuracyFloor = 13

// TestSupportBotAccuracy держит промпт из bot.go честным. 0.5B гиперчувствительна к
// формулировке: правка одной строки промпта или выброшенное из обращения слово меняют
// метку. Поэтому набор обращений заморожен, и любая правка промпта меряется на нём, а
// не обсуждается на глаз.
//
// Числа сравнимы между прогонами только при тех же параметрах инференса, что на проде:
// количество потоков меняет порядок сложений в редукциях и переставляет маргинальные
// ответы (замерено: 11 из 15 при потоках по умолчанию против 10 из 15 на одном потоке).
// Клиент задаёт их константами пакета, поэтому тест ходит через него, а не своим
// запросом.
func TestSupportBotAccuracy(t *testing.T) {
	baseURL := os.Getenv("OLLAMA_URL")
	if baseURL == "" {
		t.Skip("OLLAMA_URL is empty: no local model to ask")
	}
	model := os.Getenv("OLLAMA_MODEL")
	if model == "" {
		model = "qwen2.5:0.5b"
	}

	client := llm.New(baseURL, model)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()

	if err := client.Available(ctx); err != nil {
		t.Skipf("model %s is not ready: %v", model, err)
	}

	bot := newBot(nil, client, silentLogger{})

	cases := []struct {
		topic   string
		subject string
		body    string
	}{
		{topicAccount, "Не приходит письмо", "Забыл пароль от аккаунта. Пробовал восстановить, но письмо так и не пришло, проверял и спам. Что делать?"},
		{topicAccount, "Смена ника", "Хочу сменить никнейм, он у меня с ошибкой. И фото профиля не грузится, пишет ошибку при загрузке."},
		{topicAccount, "Вход", "Захожу с телефона и меня каждый раз выкидывает обратно на страницу входа. На компьютере всё нормально."},
		{topicDelivery, "ПВЗ", "Отнёс книгу в пункт выдачи на Ленина ещё позавчера, сотрудник принял. В приложении статус так и висит «доставляется», ничего не меняется."},
		{topicDelivery, "Не пришла вещь", "Прошло пять дней с момента подтверждения, вещь мне так и не пришла. Остальные участники вроде свои вещи отдали."},
		{topicDelivery, "Другой пункт", "Можно ли поменять пункт выдачи после того, как обмен подтвердили? Мне неудобно ехать в тот, который выбрал."},
		{topicExchange, "Статус", "Мой обмен уже неделю в статусе «предложен». Двое согласились, третий молчит. Сколько это может длиться?"},
		{topicExchange, "Отмена", "Как выйти из цепочки, если я передумал обмениваться? Не хочу подводить остальных, но обстоятельства изменились."},
		{topicExchange, "Не находит", "Разместил три вещи и указал желаемые категории, но мне ни разу не предложили ни одной цепочки. Может я что-то не так настроил?"},
		{topicComplaint, "Грубость", "Участник обмена в чате пишет мне оскорбления и угрожает. Скриншоты есть, куда их отправить?"},
		{topicComplaint, "Мошенник", "Второй участник просит перевести ему деньги на карту, говорит иначе вещь не отправит. Похоже на мошенничество."},
		{topicComplaint, "Обман", "Мне пришла совсем не та вещь, что была в объявлении, вместо наушников лежала пустая коробка."},
		{topicOther, "Приложение", "Есть ли у вас мобильное приложение для айфона? Пользоваться через браузер не очень удобно."},
		{topicOther, "Предложение", "Хочу предложить идею: добавьте возможность указывать город, чтобы не ездить через пол-Москвы."},
		// Деньги. Первый кейс до появления темы payment лежал в other и получал ответ
		// «отвечает модератор», хотя факт для ответа у сервиса есть, — с него и началась
		// шестая тема.
		{topicPayment, "Комиссия", "А сервис берёт какую-то комиссию за обмен? В условиях не нашёл ничего про оплату."},
		{topicPayment, "Оплата", "Надо ли платить за обмен?"},
		{topicPayment, "Доплата", "Участник просит доплату 500 рублей за разницу в цене вещей, это нормально или уже развод?"},
		// Пограничный намеренно: вопрос про деньги, но про деньги за доставку. Модель
		// отвечает delivery, и это не абсурд — набор держит кейс, чтобы граница между
		// двумя темами была видна, а не забылась при следующей правке промпта.
		{topicPayment, "Стоимость доставки", "Кто платит за доставку в пункт выдачи, я или получатель?"},
		// Пришёл из первой живой проверки через интерфейс и промахнулся: слово «статус»
		// перетягивает обращение в exchange. Промах известный, набор его держит
		// намеренно — иначе следующая правка промпта про него забудет.
		{topicDelivery, "Статус доставки", "Отнёс книгу в пункт выдачи на Ленина позавчера, сотрудник её принял. А статус обмена так и висит «доставляется», ничего не меняется. Что делать?"},
	}

	correct := 0
	for _, testCase := range cases {
		started := time.Now()
		got, err := bot.classify(ctx, botInput(testCase.subject, testCase.body))
		if err != nil {
			t.Fatalf("classify %q: %v", testCase.subject, err)
		}
		if got == testCase.topic {
			correct++
			t.Logf("ok    %-12s %-16s %.1fs", got, testCase.subject, time.Since(started).Seconds())
			continue
		}
		t.Logf("miss  want=%-10s got=%-10s %-16s %.1fs",
			testCase.topic, got, testCase.subject, time.Since(started).Seconds())
	}

	t.Logf("%d of %d requests routed correctly on %s", correct, len(cases), model)
	if correct < botAccuracyFloor {
		t.Fatalf(
			"routing accuracy dropped to %d of %d, floor is %d: the prompt in bot.go got worse",
			correct, len(cases), botAccuracyFloor,
		)
	}
}
