-- Признак «обращению нужен человек». Отдельная отметка, а не статус: support_thread_status
-- уже занят под жизненный цикл (`in_progress` означает «взято конкретным администратором»,
-- на этом держатся Assign, Send и Close), а эскалация с ним ортогональна — взятое в работу
-- обращение остаётся эскалированным, и наоборот.
--
-- Время, а не boolean: по нему видно, когда стало нужно вмешаться, и это тот же приём,
-- что у assigned_at, closed_at и *_read_at рядом.
--
-- Ставится в двух случаях, оба означают «автоответ не решил вопрос»:
--   1. пользователь написал в обращение повторно — то есть ответ бота не помог;
--   2. бот не справился с первого сообщения: модель отнесла обращение к теме `other`
--      либо не ответила вовсе (недоступна, таймаут, мусор вместо JSON).
ALTER TABLE support_threads
    ADD COLUMN escalated_at timestamptz;

