-- Маскот переименован в «Уми», а бот говорит от его лица, поэтому ник служебного
-- пользователя едет следом. Ник в базе и BotNickname в коде обязаны совпадать: ответ
-- бота находит автора джойном по нику, и разъехавшись они дают не ошибку, а молчание.
--
-- Отдельная миграция, а не правка 00024: та уже накатана, и переименовать нужно
-- существующую строку. Ограничение, из-за которого в 00024 появился «У-бот», новому
-- нику не мешает: в «Уми» ровно три символа, нижняя граница CHECK.
--
-- Если ник «Уми» успел занять живой пользователь, UPDATE упадёт на
-- users_nickname_lower_key и уронит миграцию. Так и надо: молчащий бот заметен только
-- по одной строке в логе, а упавший деплой — сразу.
UPDATE users SET nickname = 'Уми' WHERE lower(nickname) = lower('У-бот');

