-- Автоответчик поддержки — обычная строка в users, а не отдельная таблица: author_id у
-- support_messages ссылается на users, и служебному автору деться больше некуда.
--
-- is_admin обязателен: триггер notify_support_message выбирает получателя уведомления
-- по этому флагу, и без него ответ бота уехал бы администраторам вместо автора
-- обращения. Плата — уведомления, которые триггер заводит на бота от каждого
-- сообщения пользователя: их никто не читает, потому что войти этим пользователем
-- нельзя.
--
-- Ник виден пользователю над сообщением, поэтому он честный, а не служебный: бот не
-- притворяется человеком.
-- Ник — это имя маскота «У», от лица которого бот и говорит («Привет! Я У…»). Одной
-- буквой его назвать нельзя: users держит CHECK (char_length(nickname) BETWEEN 3 AND 32),
-- поэтому в базе «У-бот», а в тексте сообщения — «У».
INSERT INTO users (nickname, password_hash, description, is_admin)
VALUES (
    'У-бот',
    -- Заведомо не bcrypt-хеш: CompareHashAndPassword на такой строке всегда вернёт
    -- ошибку, то есть 401. Отдельный флаг «служебный аккаунт» ради этого не нужен.
    'no-login',
    'Маскот сервиса. Отвечает на обращения в поддержку автоматически, пока их не взял модератор.',
    true
);

-- +goose Down

-- author_id у support_messages стоит ON DELETE RESTRICT, поэтому сначала ответы бота.
DELETE FROM support_messages
WHERE author_id IN (SELECT id FROM users WHERE lower(nickname) = lower('У-бот'));

DELETE FROM users WHERE lower(nickname) = lower('У-бот');
